def digest(data):
    return hashlib.sha256(data).hexdigest()


def execute(script_path, temp):
    command=[sys.executable, str(script_path), '--mode', 'apply']
    result=subprocess.run(command, cwd=temp, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f'Original guarded patch failed: {script_path.name}\\n{result.stdout}\\n{result.stderr}')
    print(result.stdout.strip())


def validate_javascript(frontend_path, generator_path):
    content=frontend_path.read_text(encoding='utf-8')
    scripts=re.findall(r'<script\b[^>]*>(.*?)</script>',content,re.I|re.S)
    if len(scripts)!=5:
        raise RuntimeError(f'Expected five inline scripts in combined frontend, found {len(scripts)}')
    for i,js in enumerate(scripts):
        tmp=frontend_path.parent / f'_cosmos_check_{i}.js'
        try:
            tmp.write_text(js,encoding='utf-8')
            subprocess.run(['node','--check',str(tmp)],check=True,capture_output=True,text=True)
        finally:
            tmp.unlink(missing_ok=True)
    subprocess.run(['node','--check',str(generator_path)],check=True,capture_output=True,text=True)


